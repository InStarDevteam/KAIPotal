export interface KrmfProgressSummary {
  totalControls: number;
  appliedControls: number;
  submittedEvidence: number;
  approvedEvidence: number;
  openIssues: number;
  remediatingControls: number;
  completedControls: number;
  progressPercent: number;
  highRiskIssues: number;
}

export const summarizeKrmfProgress = (
  controls: ControlItem[],
  evidences: Evidence[],
  issues: RiskIssue[],
): KrmfProgressSummary => {
  const totalControls = controls.length;
  const completedControls = controls.filter(
    c => c.checkStatus === 'completed',
  ).length;
  return {
    totalControls,
    appliedControls: controls.filter(c => c.applied).length,
    submittedEvidence: evidences.filter(e => e.status !== 'not_submitted')
      .length,
    approvedEvidence: evidences.filter(e => e.status === 'approved').length,
    openIssues: issues.filter(i => i.status !== 'closed').length,
    remediatingControls: controls.filter(c => c.checkStatus === 'remediating')
      .length,
    completedControls,
    progressPercent: totalControls
      ? Math.round((completedControls / totalControls) * 100)
      : 0,
    highRiskIssues: issues.filter(
      i => i.severity === 'high' || i.severity === 'critical',
    ).length,
  };
};
